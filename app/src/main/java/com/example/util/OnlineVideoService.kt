/**
 * Online VIDEO support (YouTube through NewPipeExtractor, same engine as Online Music).
 *
 * A video that comes from the internet is represented everywhere in the app by a normal VideoItem whose
 * `path` is [ONLINE_VIDEO_PATH_PREFIX] + the watch URL. The player recognises that prefix, resolves the real
 * stream URLs (see [OnlineVideoService.resolveSession]) and hands them to mpv.
 */
const val ONLINE_VIDEO_PATH_PREFIX = "online-video://"

fun isOnlineVideoPath(path: String?): Boolean = path != null && path.startsWith(ONLINE_VIDEO_PATH_PREFIX)

fun onlineVideoUrlFromPath(path: String): String = path.removePrefix(ONLINE_VIDEO_PATH_PREFIX)

/** One selectable picture quality (a single stream URL). */
data class OnlineVideoOption(
    val label: String,
    val height: Int,
    val url: String,
    val fps: Int,
    val codec: String,
    /** True = picture only (audio is added separately, so any language can be chosen). */
    val isVideoOnly: Boolean
)

/** One audio language / dub of the video. */
data class OnlineAudioOption(
    val id: String,
    val label: String,
    val language: String?,
    val url: String,
    val bitrate: Int,
    val isOriginal: Boolean
)

data class OnlineSubtitleOption(
    val label: String,
    val language: String,
    val url: String,
    val isAutoGenerated: Boolean
)

/** Everything the player needs to play one online video. */
data class OnlineVideoSession(
    val videoUrl: String,
    val title: String,
    val channel: String,
    val durationSec: Long,
    val thumbnailUrl: String?,
    val videoOptions: List<OnlineVideoOption>,
    val audioOptions: List<OnlineAudioOption>,
    val subtitleOptions: List<OnlineSubtitleOption>,
    val related: List<OnlineTrackResult>,
    val resolvedAtMs: Long = System.currentTimeMillis()
) {
    val maxHeight: Int get() = videoOptions.maxOfOrNull { it.height } ?: 0

    /** "Auto" first, then every real quality from best to worst. */
    val qualityLabels: List<String>
        get() = if (videoOptions.isEmpty()) emptyList() else listOf(AUTO_QUALITY) + videoOptions.map { it.label }

    /** Auto = best quality up to 1080p (saves data and decodes smoothly on phones). */
    fun optionFor(label: String?): OnlineVideoOption? {
        if (videoOptions.isEmpty()) return null
        if (label == null || label == AUTO_QUALITY) {
            return videoOptions.firstOrNull { it.height <= 1080 } ?: videoOptions.last()
        }
        return videoOptions.firstOrNull { it.label == label } ?: optionFor(AUTO_QUALITY)
    }

    companion object {
        const val AUTO_QUALITY = "Auto"
    }
}

private fun Any.callString(name: String): String? =
    try { javaClass.getMethod(name).invoke(this) as? String } catch (_: Throwable) { null }

private fun Any.callAny(name: String): Any? =
    try { javaClass.getMethod(name).invoke(this) } catch (_: Throwable) { null }

private fun Any.callInt(name: String): Int =
    try { (javaClass.getMethod(name).invoke(this) as? Number)?.toInt() ?: 0 } catch (_: Throwable) { 0 }

private fun Any.callBool(name: String): Boolean =
    try { (javaClass.getMethod(name).invoke(this) as? Boolean) ?: false } catch (_: Throwable) { false }

object OnlineVideoService {
    private const val TAG = "OnlineVideoService"
    private const val SESSION_TTL_MS = 20 * 60 * 1000L

    private val sessionCache = ConcurrentHashMap<String, OnlineVideoSession>()
    private val maxHeightCache = ConcurrentHashMap<String, Int>()

    fun cachedMaxHeight(videoUrl: String): Int? = maxHeightCache[videoUrl]

    fun resolutionBadge(height: Int): String = when {
        height >= 4320 -> "8K"
        height >= 2160 -> "4K"
        height > 0 -> "${height}p"
        else -> ""
    }

    /** Quick guess from the title, used until the real maximum quality has been looked up. */
    fun resolutionFromTitle(title: String): String {
        val t = title.uppercase(Locale.ROOT)
        return when {
            t.contains("8K") || t.contains("4320P") -> "8K"
            t.contains("4K") || t.contains("2160P") || t.contains("UHD") -> "4K"
            t.contains("1440P") || t.contains("2K") -> "1440p"
            t.contains("1080P") || t.contains("FULL HD") || t.contains("FHD") -> "1080p"
            t.contains("720P") -> "720p"
            else -> ""
        }
    }

    private fun codecScore(codec: String): Int = when {
        codec.startsWith("avc") -> 300
        codec.startsWith("vp9") || codec.startsWith("vp09") -> 200
        codec.startsWith("av01") || codec.startsWith("av1") -> 100
        else -> 150
    }

    private fun optionScore(o: OnlineVideoOption, bitrate: Int): Int =
        (if (o.isVideoOnly) 1000 else 0) + codecScore(o.codec) + (o.fps / 10) + (bitrate / 1_000_000)

    /** Looks up every stream of a video. Cached for 20 minutes so tapping a video that was just probed is instant. */
    suspend fun resolveSession(videoUrl: String, forceRefresh: Boolean = false): OnlineVideoSession? =
        withContext(Dispatchers.IO) {
            val cached = sessionCache[videoUrl]
            if (!forceRefresh && cached != null && System.currentTimeMillis() - cached.resolvedAtMs < SESSION_TTL_MS) {
                return@withContext cached
            }
            try {
                OnlineMusicService.ensureNewPipeReady()
                val target = videoUrl.replace("music.youtube.com", "www.youtube.com")
                val info = StreamInfo.getInfo(ServiceList.YouTube, target)

                // ---- Picture qualities -------------------------------------------------------
                val adaptive = HashMap<Int, Pair<OnlineVideoOption, Int>>()
                val muxedByHeight = HashMap<Int, Pair<OnlineVideoOption, Int>>()

                fun consider(
                    stream: org.schabi.newpipe.extractor.stream.VideoStream,
                    videoOnly: Boolean,
                    into: HashMap<Int, Pair<OnlineVideoOption, Int>>
                ) {
                    if (!stream.isUrl) return
                    val url = stream.content
                    if (url.isNullOrBlank()) return
                    val res = stream.resolution ?: ""
                    val h = Regex("(\\d{3,4})p").find(res)?.groupValues?.get(1)?.toIntOrNull()
                        ?: stream.callInt("getHeight")
                    if (h <= 0) return
                    val fps = Regex("p(\\d{2,3})").find(res)?.groupValues?.get(1)?.toIntOrNull() ?: 0
                    val codec = (stream.callString("getCodec") ?: "").lowercase(Locale.ROOT)
                    val bitrate = stream.callInt("getBitrate")
                    val opt = OnlineVideoOption(
                        label = "${h}p",
                        height = h,
                        url = url,
                        fps = fps,
                        codec = codec,
                        isVideoOnly = videoOnly
                    )
                    val existing = into[h]
                    if (existing == null || optionScore(opt, bitrate) > optionScore(existing.first, existing.second)) {
                        into[h] = opt to bitrate
                    }
                }

                (info.videoOnlyStreams ?: emptyList()).forEach { consider(it, true, adaptive) }
                (info.videoStreams ?: emptyList()).forEach { consider(it, false, muxedByHeight) }

                val options = ArrayList<OnlineVideoOption>()
                adaptive.values.forEach { options.add(it.first) }
                muxedByHeight.forEach { (h, v) -> if (!adaptive.containsKey(h)) options.add(v.first) }
                options.sortByDescending { it.height }

                // ---- Audio languages --------------------------------------------------------
                val audioOptions = ArrayList<OnlineAudioOption>()
                (info.audioStreams ?: emptyList())
                    .filter { it.isUrl && !it.content.isNullOrBlank() }
                    .groupBy { it.callString("getAudioTrackId") ?: "default" }
                    .forEach { (id, list) ->
                        val best = list.maxByOrNull { it.averageBitrate } ?: return@forEach
                        val name = best.callString("getAudioTrackName")
                        val locale = best.callAny("getAudioLocale") as? Locale
                        val lang = locale?.language?.takeIf { it.isNotBlank() }
                        val typeName = best.callAny("getAudioTrackType")?.toString() ?: ""
                        val label = when {
                            !name.isNullOrBlank() -> name
                            locale != null && locale.getDisplayLanguage(Locale.ENGLISH).isNotBlank() ->
                                locale.getDisplayLanguage(Locale.ENGLISH)
                            else -> "Original audio"
                        }
                        val isOriginal = typeName.equals("ORIGINAL", true) ||
                            label.contains("original", true) || id == "default"
                        audioOptions.add(
                            OnlineAudioOption(
                                id = id,
                                label = label,
                                language = lang,
                                url = best.content,
                                bitrate = best.averageBitrate,
                                isOriginal = isOriginal
                            )
                        )
                    }
                audioOptions.sortWith(compareByDescending<OnlineAudioOption> { it.isOriginal }.thenBy { it.label })

                // ---- Subtitles --------------------------------------------------------------
                val subtitleOptions = ArrayList<OnlineSubtitleOption>()
                (info.subtitles ?: emptyList())
                    .filter { it.isUrl && !it.content.isNullOrBlank() }
                    .groupBy { (it.callString("getLanguageTag") ?: "und") to it.callBool("isAutoGenerated") }
                    .forEach { (key, list) ->
                        val chosen = list.firstOrNull { it.format?.suffix.equals("vtt", true) } ?: list.first()
                        val display = chosen.callString("getDisplayLanguageName") ?: key.first
                        subtitleOptions.add(
                            OnlineSubtitleOption(
                                label = if (key.second) "$display (auto)" else display,
                                language = key.first,
                                url = chosen.content,
                                isAutoGenerated = key.second
                            )
                        )
                    }
                subtitleOptions.sortWith(compareBy<OnlineSubtitleOption> { it.isAutoGenerated }.thenBy { it.label })

                val related = (info.relatedItems ?: emptyList())
                    .filterIsInstance<StreamInfoItem>()
                    .filter { it.url.isNotBlank() && it.duration > 60L }
                    .map { item ->
                        OnlineTrackResult(
                            videoUrl = item.url,
                            title = item.name?.takeIf { it.isNotBlank() } ?: "",
                            artist = item.uploaderName ?: "",
                            durationSec = item.duration.coerceAtLeast(0L),
                            thumbnailUrl = OnlineMusicService.extractBestThumbnailUrl(item.thumbnails, item.url),
                            viewCount = item.viewCount.coerceAtLeast(0L)
                        )
                    }

                val session = OnlineVideoSession(
                    videoUrl = videoUrl,
                    title = info.name ?: "",
                    channel = info.uploaderName ?: "",
                    durationSec = info.duration.coerceAtLeast(0L),
                    thumbnailUrl = OnlineMusicService.extractBestThumbnailUrl(info.thumbnails, videoUrl),
                    videoOptions = options,
                    audioOptions = audioOptions,
                    subtitleOptions = subtitleOptions.take(24),
                    related = related
                )
                if (session.maxHeight > 0) maxHeightCache[videoUrl] = session.maxHeight
                sessionCache[videoUrl] = session
                session
            } catch (e: Exception) {
                Log.e(TAG, "resolveSession('$videoUrl') failed: ${e.message}", e)
                null
            }
        }

    /** Highest available picture quality of a video (looked up lazily for the cards of the first results). */
    suspend fun probeMaxHeight(videoUrl: String): Int {
        maxHeightCache[videoUrl]?.let { return it }
        return resolveSession(videoUrl)?.maxHeight ?: 0
    }
}

/** What the user watched online: drives "recommended for you" (favourite channels / topics). */
object OnlineVideoHistory {
    private const val PREFS = "online_video_history_v1"
    private const val KEY = "items"
    private const val MAX_ITEMS = 80

    @Synchronized
    fun record(context: Context, url: String, title: String, channel: String) {
        try {
            val prefs = context.applicationContext.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            val old = JSONArray(prefs.getString(KEY, "[]") ?: "[]")
            val out = JSONArray()
            val first = JSONObject()
                .put("url", url).put("title", title).put("channel", channel)
                .put("ts", System.currentTimeMillis())
            out.put(first)
            for (i in 0 until old.length()) {
                if (out.length() >= MAX_ITEMS) break
                val o = old.optJSONObject(i) ?: continue
                if (o.optString("url") != url) out.put(o)
            }
            prefs.edit().putString(KEY, out.toString()).apply()
        } catch (_: Throwable) {}
    }

    private fun load(context: Context): List<JSONObject> = try {
        val arr = JSONArray(
            context.applicationContext.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
                .getString(KEY, "[]") ?: "[]"
        )
        (0 until arr.length()).mapNotNull { arr.optJSONObject(it) }
    } catch (_: Throwable) { emptyList() }

    /** Most watched channels; newer watches count a little more. */
    fun topChannels(context: Context, limit: Int): List<String> {
        val scores = LinkedHashMap<String, Double>()
        load(context).forEachIndexed { index, o ->
            val ch = o.optString("channel").trim()
            if (ch.isNotEmpty()) scores[ch] = (scores[ch] ?: 0.0) + 1.0 + (MAX_ITEMS - index).coerceAtLeast(0) / MAX_ITEMS.toDouble()
        }
        return scores.entries.sortedByDescending { it.value }.take(limit).map { it.key }
    }

    fun recentTitles(context: Context, limit: Int): List<String> =
        load(context).take(limit).map { it.optString("title") }.filter { it.isNotBlank() }
}

/**
 * Endless "Recommended for you" feed for online videos: ~65% like what the user watches (their channels and
 * the topics of recently watched videos), ~35% discovery from other topics. Videos only, no audio-only content.
 */
object OnlineVideoRecommender {
    private val discoveryTopics = listOf(
        "trending videos today", "best anime episodes", "new movie trailers", "full documentary",
        "technology review", "gaming highlights", "official music video", "comedy sketches",
        "easy cooking recipes", "travel vlog 4k", "science explained", "sports highlights",
        "short film", "podcast clips", "nature 4k", "stand up comedy"
    )

    private fun keywordQuery(title: String): String {
        val words = title.replace(Regex("[\\[\\](){}|•\\-–—_]"), " ")
            .split(Regex("\\s+")).filter { it.length > 2 }
        return words.take(4).joinToString(" ")
    }

    private fun mix(similar: List<OnlineTrackResult>, discovery: List<OnlineTrackResult>): List<OnlineTrackResult> {
        val out = ArrayList<OnlineTrackResult>(similar.size + discovery.size)
        var si = 0
        var di = 0
        var i = 0
        while (si < similar.size || di < discovery.size) {
            val takeDiscovery = (i % 3 == 2 && di < discovery.size) || si >= similar.size
            if (takeDiscovery) out.add(discovery[di++]) else out.add(similar[si++])
            i++
        }
        return out
    }

    suspend fun fetchFeedBatch(
        context: Context,
        excludeUrls: Set<String>,
        usedQueries: MutableSet<String>
    ): List<OnlineTrackResult> = coroutineScope {
        val channels = OnlineVideoHistory.topChannels(context, 4)
        val topics = OnlineVideoHistory.recentTitles(context, 4).map { keywordQuery(it) }
        val similarQueries = (channels + topics)
            .filter { it.isNotBlank() && usedQueries.add(it.lowercase(Locale.ROOT)) }
            .take(2)

        val freshTopics = discoveryTopics.filter { !usedQueries.contains(it) }.shuffled()
        val discoveryQueries = freshTopics.take(if (similarQueries.isEmpty()) 3 else 1)
        discoveryQueries.forEach { usedQueries.add(it) }

        val similarJobs = similarQueries.map { q -> async { try { OnlineMusicService.search(q) } catch (_: Throwable) { emptyList() } } }
        val discoveryJobs = discoveryQueries.map { q -> async { try { OnlineMusicService.search(q) } catch (_: Throwable) { emptyList() } } }

        fun accept(r: OnlineTrackResult) =
            r.videoUrl !in excludeUrls && r.title.isNotBlank() && r.durationSec in 61L..14_400L

        val similar = similarJobs.awaitAll().flatten().filter(::accept).distinctBy { it.videoUrl }
        val discovery = discoveryJobs.awaitAll().flatten().filter(::accept).distinctBy { it.videoUrl }
        mix(similar, discovery.filter { d -> similar.none { it.videoUrl == d.videoUrl } })
    }
}
